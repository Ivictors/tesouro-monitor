CREATE TABLE ativos_carteira (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_titulo VARCHAR(255),
    data_compra DATE,
    taxa_contratada NUMERIC(38, 2),
    preco_compra NUMERIC(38, 2),
    quantidade NUMERIC(38, 2)
);

CREATE TABLE cotacoes_diarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_ativo VARCHAR(255),
    data_cotacao DATE,
    taxa_atual NUMERIC(38, 2),
    preco_compra_atual NUMERIC(38, 2),
    preco_resgate_atual NUMERIC(38, 2),
    CONSTRAINT uk_cotacao_ativo_data UNIQUE (nome_ativo, data_cotacao)
);
