CREATE TABLE alertas_monitoramento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id BIGINT NOT NULL,
    cotacao_id BIGINT NOT NULL,
    nome_ativo VARCHAR(255) NOT NULL,
    data_cotacao DATE NOT NULL,
    percentual_observado NUMERIC(12, 2) NOT NULL,
    regra_aplicada VARCHAR(64) NOT NULL,
    limite_percentual NUMERIC(12, 2) NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    lido BOOLEAN NOT NULL DEFAULT FALSE,
    lido_em TIMESTAMP,
    CONSTRAINT fk_alerta_ativo FOREIGN KEY (ativo_id) REFERENCES ativos_carteira(id) ON DELETE CASCADE,
    CONSTRAINT fk_alerta_cotacao FOREIGN KEY (cotacao_id) REFERENCES cotacoes_diarias(id) ON DELETE CASCADE,
    CONSTRAINT uk_alerta_ativo_cotacao UNIQUE (ativo_id, cotacao_id)
);

CREATE INDEX idx_alertas_criado_em ON alertas_monitoramento (criado_em DESC);
